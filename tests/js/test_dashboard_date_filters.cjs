const fs=require('fs'),vm=require('vm'),assert=require('assert');
const root=__dirname+'/../..';
const app=fs.readFileSync(root+'/static/app.js','utf8');
const helper=app.match(/window\.o24CasablancaDay = function \(date = new Date\(\)\) \{[\s\S]*?\n\};/);
assert(helper,'Shared Casablanca date helper is wired in app.js');
const FixedDate=class extends Date{constructor(...args){super(...(args.length?args:['2026-10-25T23:30:00.000Z']))}static now(){return new Date('2026-10-25T23:30:00.000Z').getTime()}};
const ctx=vm.createContext({window:{},Date:FixedDate,renderView:()=>{ctx.rendered=(ctx.rendered||0)+1},opsPeriod:{from:'',to:''}});
vm.runInContext(helper[0],ctx);
assert.equal(ctx.window.o24CasablancaDay(new FixedDate()),'2026-10-26','Morocco day must not roll back to UTC yesterday near midnight');
const logistics=fs.readFileSync(root+'/static/logistics.js','utf8');
const ops=logistics.split('\n').find(line=>line.startsWith('function opsDays('));
assert(ops,'Operational analytics quick date-range handler exists');
vm.runInContext(ops,ctx);vm.runInContext('opsDays(7)',ctx);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.opsPeriod)),{from:'2026-10-20',to:'2026-10-26'});
assert.equal(ctx.rendered,1);
const driver=fs.readFileSync(root+'/static/driver-app.js','utf8');
assert(driver.includes("window.o24CasablancaDay(d)"),'Courier app date filters use Morocco calendar day');
assert(driver.includes("const to = iso(new Date()), from = new Date(to + 'T12:00:00Z')"),'Courier app range uses calendar arithmetic');
const ramassage=fs.readFileSync(root+'/static/ramassage-map.js','utf8');
assert(ramassage.includes("window.o24CasablancaDay?.(new Date())"),'Ramassage history defaults to Morocco date');
console.log('PASS: Morocco-local day boundaries, 7-day operations preset, courier date filter and ramassage history date');
