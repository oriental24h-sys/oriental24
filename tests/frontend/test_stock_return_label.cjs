const fs=require('fs'),vm=require('vm'),assert=require('assert');
const src=fs.readFileSync('static/operations.js','utf8');
const labelFn=src.slice(src.indexOf('function labelMarkup('),src.indexOf('\nasync function printPreparedLabels('));
const ctx=vm.createContext({esc:String,money:String,date:String,parcelPolicyBadges:()=>'',icon:()=>''});
vm.runInContext(labelFn,ctx);
const stock={city:'Agadir',tracking:'CMD-STOCK-1',qr:'qr-data',barcode:'barcode-data',recipient:'Test Recipient',phone:'0600000000',address:'Agadir',amount:250,company:'Boutique Test',client:'Client',product:'SKU-A × 2',stock_return_required:1,stock_order_id:37,stock_lines:[{sku:'SKU-A',name:'Produit A',quantity:2}],created_at:'2026-10-26'};
ctx.stock=stock;
const label=vm.runInContext('labelMarkup(stock)',ctx);
for(const text of ['SKU / QUANTITÉ','SKU-A','Produit A × 2','RETOUR AU STOCK — PAS AU CLIENT','Hub Central','Retour vers Hub Central','réintégration auto au scan','PREP-00037'])assert(label.includes(text),text);
assert.equal(vm.runInContext('labelIsLong(stock)',ctx),false);
const regular={...stock,stock_return_required:0,stock_lines:[],stock_order_id:null};
ctx.regular=regular;
const ordinary=vm.runInContext('labelMarkup(regular)',ctx);
assert(!ordinary.includes('RETOUR AU STOCK'));
assert.equal(vm.runInContext('labelIsLong(regular)',ctx),false);
const reception=fs.readFileSync('static/reception-collection.js','utf8');
assert(reception.includes('Palette retour vers Hub Central'));
assert(reception.includes('result.stock_restocked?.length'));
console.log('PASS: stock labels keep the normal A6 shape (compact SKU + 2-line return warning); return-palette reception reports automatic restock');
